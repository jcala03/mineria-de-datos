def contar_iqr(datos, columnas):
    resumen = []
    for nombre in columnas:
        x = datos[nombre]
        q1, q3 = x.quantile([0.25,0.75])
        rango = q3 - q1
        n = int(((x < q1-1.5*rango) | (x > q3+1.5*rango)).sum())
        resumen.append({'variable':nombre, 'posibles_atipicos_IQR':n})
    return pd.DataFrame(resumen)

